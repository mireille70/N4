export type SectionBlock =
  | { type: 'voice'; id: string; title: string; items: VoiceApp[] }
  | { type: 'promo'; id: string; slides: { image: string; alt: string; to: string }[] }
  | { type: 'showcase'; id: string; title: string; products: string[]; viewAll: { label: string; to: string } }
  | { type: 'reviews';id: string; title: string; score: number; count: string; items: Review[] }
  | { type: 'hero'; id: string; slides: HeroSlide[]; promos: { offers: string; arrivals: string; shopping: string } }
  | { type: 'wall-hero'; id: string; slides: HeroSlide[] }
  | { type: 'deck-hero'; id: string; slides: HeroSlide[] }
  | { type: 'tunnel-hero'; id: string; slides: HeroSlide[] }
  | { type: 'gift-hero'; id: string; slides: HeroSlide[] }
  | { type: 'mascot-hero'; id: string; content: HeroContent }
  | { type: 'features'; id: string; items: FeatureItem[] }
  | { type: 'offers'; id: string; title: string; endsLabel: string; viewAll: { label: string; to: string } }
  | { type: 'categories'; id: string; title?: string }
  | { type: 'popular'; id: string; title: string; products: string[]; viewAll: { label: string; to: string } }
  | { type: 'products'; id: string; title: string; products: string[]; viewAll: { label: string; to: string } }
  | { type: 'platforms'; id: string; title: string; products: string[] }
  | { type: 'arrivals'; id: string; title: string; products: string[] }
  | { type: 'shopping'; id: string; title: string; products: string[]; viewAll: { label: string; to: string } };

