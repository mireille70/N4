/**
 * HOMEPAGE COMPOSITION — an ordered list of section blocks.
 * Each block maps to a reusable section component (see sections/registry.tsx),
 * so a page builder can reorder, remove or duplicate them freely.
 */

export interface HeroSlide {
  id: string;
  /** Headline lines; the `highlight` word gets the accent colour */
  lines: string[];
  highlight?: string;
  cta: { label: string; to: string };
  secondary?: { label: string; to: string };
  /**
   * The slide's card image — one upload per slide. Portrait 3:4, transparent
   * PNG/WebP recommended; upload at the highest resolution available (4K ideal).
   */
  art: string;
  /** Optional lighter rendition used on standard-density screens */
  artSmall?: string;
  /** Where the card's popup links */
  to: string;
  /** Latin label for the slide (accessibility + thumbnails) */
  label: string;
}

/** Copy for the alternative mascot hero (sections/MascotHero.tsx) */
export interface HeroContent {
  title: string;
  subtitle: string;
  searchPlaceholder: string;
}

/** One of the minimal feature cards (sections/FeatureCards.tsx) */
export interface FeatureItem {
  icon: 'bolt' | 'cart' | 'grid';
  title: string;
  text: string;
}

/** One customer review (sections/ReviewsSection.tsx) — demo content, replace with real reviews */
export interface Review {
  name: string;
  rating: number;
  text: string;
  /** catalog product the reviewer bought */
  slug: string;
  pack?: string;
  when: string;
}

/** A voice / social app tile (sections/VoiceProducts.tsx, also the hero panels). Art: public/assets/hero/apps/<slug>.webp */
export interface VoiceApp {
  slug: string;
  name: string;
  nameEn: string;
  to: string;
  /** brand colour of the app icon — drives the glow behind its tile */
  color: string;
}

